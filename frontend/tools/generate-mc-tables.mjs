// Writes src/app/voxel/mc-tables.ts from the lookup table that ships with three.js,
// so the worker does not have to pull in the three.js module graph at runtime.
import { writeFileSync } from 'node:fs';
import { triTable } from 'three/examples/jsm/objects/MarchingCubes.js';

if (triTable.length !== 256 * 16) throw new Error(`unexpected table size ${triTable.length}`);
const rows = [];
for (let i = 0; i < 256; i++) {
  rows.push('  ' + Array.from(triTable.subarray(i * 16, i * 16 + 16)).join(', ') + ',');
}
writeFileSync(
  new URL('../src/app/voxel/mc-tables.ts', import.meta.url),
  `// GENERATED by tools/generate-mc-tables.mjs. Do not edit by hand.
//
// Marching cubes triangle table (Lorensen & Cline 1987, in Paul Bourke's public-domain
// formulation), copied from three.js (MIT licence, examples/jsm/objects/MarchingCubes.js).
//
// 256 cube configurations x 16 entries. Each row lists up to five triangles as triples of
// cube-edge numbers (0..11) and is terminated by -1.
// prettier-ignore
export const TRI_TABLE = new Int8Array([
${rows.join('\n')}
]);
`,
);
console.log('mc-tables.ts written');
